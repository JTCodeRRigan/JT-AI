let _lang = 'en';

export function detectDefault() {
  try { return (chrome.i18n.getUILanguage() || '').toLowerCase().startsWith('ru') ? 'ru' : 'en'; }
  catch { return 'en'; }
}
export function getLang() { return _lang; }
export function useLang(l) { if (l && STR[l]) _lang = l; }
export async function initI18n() {
  try { const s = await chrome.storage.local.get('lang'); _lang = (s.lang && STR[s.lang]) ? s.lang : detectDefault(); } catch { _lang = detectDefault(); }
  try { chrome.storage.onChanged.addListener((c, area) => { if (area === 'local' && c.lang) _lang = (c.lang.newValue && STR[c.lang.newValue]) ? c.lang.newValue : detectDefault(); }); } catch {}
  return _lang;
}
export async function setLang(l) { if (STR[l]) { _lang = l; try { await chrome.storage.local.set({ lang: l }); } catch {} } }
export function t(key, ...args) {
  const table = STR[_lang] || STR.en;
  let v = table[key]; if (v == null) v = STR.en[key]; if (v == null) return key;
  return typeof v === 'function' ? v(...args) : v;
}
export function applyI18n(root = document) {
  root.querySelectorAll('[data-i18n]').forEach((el) => { el.textContent = t(el.getAttribute('data-i18n')); });
  root.querySelectorAll('[data-i18n-html]').forEach((el) => { el.innerHTML = t(el.getAttribute('data-i18n-html')); });
  root.querySelectorAll('[data-i18n-title]').forEach((el) => { el.title = t(el.getAttribute('data-i18n-title')); });
  root.querySelectorAll('[data-i18n-ph]').forEach((el) => { el.placeholder = t(el.getAttribute('data-i18n-ph')); });
  try { document.documentElement.lang = _lang; } catch {}
}
